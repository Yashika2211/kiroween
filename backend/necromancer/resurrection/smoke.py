"""Generate tests for the resurrected repository.

* Smoke tests: every importable module must import on Python 3.12.
* Property tests (where possible): for top-level functions whose parameters all have simple
  literal defaults or simple annotations, hypothesis checks that the resurrected function
  returns the same value (or raises the same exception type) as a frozen copy of the original.

The generated files are plain pytest modules that run inside the sandbox.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass
from pathlib import Path

from necromancer.pyparse import parse_quietly
from necromancer.workspace import iter_python_files, read_text

SMOKE_PATH = "tests/test_necromancer_smoke.py"
PROPERTY_PATH = "tests/test_necromancer_properties.py"
ORIGINALS_DIR = "tests/_necromancer_originals"

_SKIP_TOP_LEVEL = {
    "setup.py",
    "conftest.py",
    "fabfile.py",
    "manage.py",
    "tasks.py",
    "noxfile.py",
    "bootstrap.py",
    "ez_setup.py",
    "distribute_setup.py",
}
_SKIP_DIRS = {"tests", "test", "docs", "doc", "examples", "example", "scripts", "benchmarks"}

_STRATEGIES = {
    "int": "st.integers(min_value=-1000, max_value=1000)",
    "float": "st.floats(allow_nan=False, allow_infinity=False, width=32)",
    "str": "st.text(max_size=20)",
    "bool": "st.booleans()",
    "list": "st.lists(st.integers(min_value=-100, max_value=100), max_size=10)",
}


def _is_test_file(rel: Path) -> bool:
    name = rel.name
    return name.startswith("test_") or name.endswith("_test.py") or name == "tests.py"


def discover_modules(root: Path) -> list[str]:
    """Dotted names of importable, non-test modules in the repository."""
    modules: list[str] = []
    for path in iter_python_files(root):
        rel = path.relative_to(root)
        parts = list(rel.parts)
        if _is_test_file(rel) or parts[-1] == "__main__.py":
            continue
        if parts[0] == "src" and len(parts) > 1:
            parts = parts[1:]
            base = root / "src"
        else:
            base = root
        if len(parts) == 1:
            if parts[0] in _SKIP_TOP_LEVEL or not parts[0][:-3].isidentifier():
                continue
            modules.append(parts[0][:-3])
            continue
        if any(p in _SKIP_DIRS for p in parts[:-1]):
            continue
        # Every directory on the way down must be a package.
        if not all(
            (base.joinpath(*parts[:i]) / "__init__.py").is_file() for i in range(1, len(parts))
        ):
            continue
        dotted = [p for p in parts[:-1]]
        if parts[-1] != "__init__.py":
            dotted.append(parts[-1][:-3])
        if all(p.isidentifier() for p in dotted):
            modules.append(".".join(dotted))
    return sorted(set(modules))


def render_smoke_tests(modules: list[str]) -> str:
    listing = "\n".join(f"    {m!r}," for m in modules)
    return f'''"""Smoke tests generated by Necromancer: every module must import on Python 3.12."""

import importlib

import pytest

MODULES = [
{listing}
]


@pytest.mark.parametrize("name", MODULES)
def test_module_imports(name):
    importlib.import_module(name)
'''


@dataclass(frozen=True)
class PureFunction:
    module: str
    name: str
    params: list[tuple[str, str]]  # (param name, strategy expression)


def _strategy_for(arg: ast.arg, default: ast.expr | None) -> str | None:
    if arg.annotation is not None and isinstance(arg.annotation, ast.Name):
        return _STRATEGIES.get(arg.annotation.id)
    if isinstance(default, ast.Constant) and type(default.value) in (int, float, str, bool):
        return _STRATEGIES[type(default.value).__name__]
    if isinstance(default, ast.List):
        return _STRATEGIES["list"]
    return None


_IMPURE_CALLS = {"open", "print", "input", "exec", "eval", "exit", "quit", "__import__"}
_IMPURE_MODULES = {"os", "sys", "subprocess", "socket", "requests", "time", "random", "shutil"}


def _root_name(node: ast.expr) -> str | None:
    while isinstance(node, ast.Attribute):
        node = node.value
    return node.id if isinstance(node, ast.Name) else None


def _looks_pure(fn: ast.FunctionDef) -> bool:
    for node in ast.walk(fn):
        if isinstance(node, (ast.Global, ast.Nonlocal, ast.Yield, ast.YieldFrom, ast.Await)):
            return False
        if isinstance(node, ast.Call):
            func = node.func
            if isinstance(func, ast.Name) and func.id in _IMPURE_CALLS:
                return False
            if isinstance(func, ast.Attribute) and _root_name(func) in _IMPURE_MODULES:
                return False
    return True


def find_pure_functions(source: str, module: str) -> list[PureFunction]:
    try:
        tree = parse_quietly(source)
    except SyntaxError:
        return []
    found: list[PureFunction] = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef) or node.name.startswith("_"):
            continue
        args = node.args
        if args.vararg or args.kwarg or args.kwonlyargs or args.posonlyargs or not args.args:
            continue
        defaults: list[ast.expr | None] = [None] * (len(args.args) - len(args.defaults))
        defaults += list(args.defaults)
        params: list[tuple[str, str]] = []
        for arg, default in zip(args.args, defaults, strict=True):
            strategy = _strategy_for(arg, default)
            if strategy is None:
                break
            params.append((arg.arg, strategy))
        else:
            if node.decorator_list or not _looks_pure(node):
                continue
            found.append(PureFunction(module=module, name=node.name, params=params))
    return found


def _has_relative_imports(source: str) -> bool:
    try:
        tree = parse_quietly(source)
    except SyntaxError:
        return True
    return any(isinstance(n, ast.ImportFrom) and n.level for n in ast.walk(tree))


def module_path(root: Path, module: str) -> Path | None:
    base = (
        root / "src"
        if (root / "src").is_dir() and not (root / module.split(".")[0]).exists()
        else root
    )
    as_file = base.joinpath(*module.split(".")).with_suffix(".py")
    if as_file.is_file():
        return as_file
    as_pkg = base.joinpath(*module.split(".")) / "__init__.py"
    return as_pkg if as_pkg.is_file() else None


def plan_property_tests(
    before: Path, after: Path, modules: list[str], limit: int = 12
) -> tuple[list[PureFunction], dict[str, str]]:
    """Pick functions to compare and the original sources to freeze.

    Returns (functions, originals) where originals maps a flat file name to source text.
    """
    functions: list[PureFunction] = []
    originals: dict[str, str] = {}
    for module in modules:
        old_path, new_path = module_path(before, module), module_path(after, module)
        if old_path is None or new_path is None:
            continue
        old_src = read_text(old_path)
        if _has_relative_imports(old_src):
            continue
        new_names = {f.name for f in find_pure_functions(read_text(new_path), module)}
        for fn in find_pure_functions(old_src, module):
            if fn.name in new_names and len(functions) < limit:
                functions.append(fn)
                originals[module.replace(".", "__") + ".py"] = old_src
    return functions, originals


def render_property_tests(functions: list[PureFunction]) -> str:
    blocks = []
    for i, fn in enumerate(functions):
        flat = fn.module.replace(".", "__")
        givens = ", ".join(f"{name}={strategy}" for name, strategy in fn.params)
        names = ", ".join(name for name, _ in fn.params)
        blocks.append(
            f"""

@settings(max_examples=60, deadline=None, suppress_health_check=list(HealthCheck))
@given({givens})
def test_{i}_{fn.name}_matches_original({names}):
    new = importlib.import_module({fn.module!r}).{fn.name}
    old = _original({flat!r}).{fn.name}
    _same(lambda: old({names}), lambda: new({names}))"""
        )
    return (
        '''"""Property tests generated by Necromancer.

Each test feeds hypothesis-generated inputs to a resurrected function and to a frozen copy of
the original, and checks they agree (same result, or same exception type).
"""

import importlib
import importlib.util
import math
from pathlib import Path

import pytest
from hypothesis import HealthCheck, given, settings
from hypothesis import strategies as st

ORIGINALS = Path(__file__).parent / "_necromancer_originals"


def _original(flat_name):
    spec = importlib.util.spec_from_file_location(
        "necromancer_original_" + flat_name, ORIGINALS / (flat_name + ".py")
    )
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except Exception as exc:  # the original may depend on APIs that no longer exist
        pytest.skip(f"original module does not import on Python 3.12: {exc!r}")
    return module


def _same(old_call, new_call):
    try:
        expected = old_call()
    except Exception as exc:
        with pytest.raises(type(exc)):
            new_call()
        return
    actual = new_call()
    if isinstance(expected, float) and isinstance(actual, float):
        assert actual == expected or math.isclose(actual, expected, rel_tol=1e-9) or (
            math.isnan(actual) and math.isnan(expected)
        )
    else:
        assert actual == expected
'''
        + "".join(blocks)
        + "\n"
    )


@dataclass(frozen=True)
class GeneratedTests:
    files: dict[str, str]  # relative path -> content
    modules: list[str]
    properties: list[PureFunction]


def generate_tests(before: Path, after: Path) -> GeneratedTests:
    modules = discover_modules(after)
    files: dict[str, str] = {}
    if modules:
        files[SMOKE_PATH] = render_smoke_tests(modules)
    functions, originals = plan_property_tests(before, after, modules)
    if functions:
        files[PROPERTY_PATH] = render_property_tests(functions)
        for flat, source in originals.items():
            files[f"{ORIGINALS_DIR}/{flat}"] = source
        files[f"{ORIGINALS_DIR}/__init__.py"] = ""
        # pytest must not collect the frozen originals as tests
        files[f"{ORIGINALS_DIR}/conftest.py"] = 'collect_ignore_glob = ["*.py"]\n'
    return GeneratedTests(files=files, modules=modules, properties=functions)
